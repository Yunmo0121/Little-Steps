'use strict';
const assert=require('node:assert/strict');
const E=require('../season2-tides-engine.js');
assert.equal(E.WIDTH,9);
assert.equal(E.HEIGHT,7);
assert.equal(E.PHASE_COUNT,4);
assert.equal(E.ACTION_COUNT,5);
assert.equal(E.STATE_COUNT,E.WIDTH*E.HEIGHT*4);
assert.equal(E.tile(E.position(3,3)),'T');
const firstWait=E.transition(E.INITIAL,4);
assert.equal(E.decode(firstWait.next).phase,1);
assert.equal(E.decode(firstWait.next).pos,E.START);
assert.equal(firstWait.reward,-.28);
const blockedHigh=E.transition(E.encode(E.position(3,2),2),1);
assert.equal(blockedHigh.hit,true);
assert.equal(blockedHigh.reason,'high-tide');
assert.equal(E.decode(blockedHigh.next).phase,3);
assert.equal(E.decode(blockedHigh.next).pos,E.position(3,2));
const swept=E.transition(E.encode(E.position(3,2),1),1);
assert.equal(swept.swept,true);
assert.equal(E.decode(swept.next).pos,E.START);
assert.equal(swept.reward,-5.5);
const crossing=E.transition(E.encode(E.position(3,2),0),1);
assert.equal(E.decode(crossing.next).pos,E.position(3,3));
assert.equal(E.decode(crossing.next).phase,1);
const done=E.transition(E.encode(E.position(1,5),0),1);
assert.equal(done.done,true);
assert.equal(done.reward,40);
const bfs=E.search(),dijkstra=E.search(true);
assert(bfs.success&&dijkstra.success);
assert.equal(bfs.steps,10);
assert.equal(bfs.waits,0);
assert.equal(dijkstra.waits,2);
assert(dijkstra.cost<bfs.cost);
for(const method of ['qlearning','sarsa']){
  const q=E.emptyQ(),qSplit=E.emptyQ();
  const rng=E.createRng(42),split=E.createRng(42);
  const options={alpha:.24,gamma:.97,epsilon:.65,decay:.994,minEpsilon:.045};
  const full=E.train(q,1500,method,options,rng);
  const part1=E.train(qSplit,200,method,{...options,startAt:0},split);
  const part2=E.train(qSplit,1300,method,{...options,startAt:200},split);
  assert.deepEqual(q,qSplit,`${method}: chunking changed Q table`);
  assert.deepEqual(full,[...part1,...part2],`${method}: chunking changed history`);
  assert.equal(rng.state(),split.state());
  assert(full.slice(-50).filter(r=>r.success).length>=45,`${method}: insufficient learning success`);
  const route=E.rollout(q);
  assert(route.success,`${method} greedy route failed`);
  assert(route.visits.some(s=>E.decode(s).phase===2),`${method}: phases not advancing`);
  console.log(method,`success: ${full.slice(-50).filter(r=>r.success).length}/50; greedy ${route.steps} actions, ${route.waits} waits`);
}
console.log('PASS — Tidal Island MDP, waiting, tides, swept states, time-aware planning, deterministic RL');
